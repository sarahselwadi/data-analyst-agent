"""
Azure Blob Storage service for storing session files with organized folder structure.
Uses Azure CLI identity authentication for secure access.
"""

import os
import logging
from datetime import datetime, timedelta
from typing import Optional, Dict, Any
from azure.storage.blob import BlobServiceClient, generate_blob_sas, BlobSasPermissions
from azure.identity import DefaultAzureCredential
from azure.core.exceptions import AzureError
from dotenv import load_dotenv

# Load environment variables
load_dotenv()

class BlobStorageService:
    """
    Azure Blob Storage service for managing session files.
    
    Enhanced folder structure: {session-id}/{subfolder}/{file}
    Subfolders:
    - user-uploads: Files uploaded by users
    - imgs: Images generated by agent (charts, visualizations)
    - files-gen: Files generated by agent (CSV, Excel, reports)
    
    Example: web-session-123/imgs/generated_chart_001.png
    """
    
    # Subfolder constants for organized storage
    SUBFOLDER_USER_UPLOADS = "user-uploads"
    SUBFOLDER_IMAGES = "imgs"
    SUBFOLDER_FILES_GEN = "files-gen"
    
    def __init__(self, account_url: str = None, container_name: str = None):
        """
        Initialize blob storage service with CLI authentication.
        
        Args:
            account_url: Azure storage account URL
            container_name: Container name for storing files
        """
        self.account_url = account_url or os.getenv("AZURE_STORAGE_ACCOUNT_URL")
        self.container_name = container_name or os.getenv("AZURE_STORAGE_CONTAINER_NAME", "data-analyst-session-files")
        
        # Use Azure CLI identity authentication
        self.credential = DefaultAzureCredential()
        
        try:
            self.blob_service_client = BlobServiceClient(
                account_url=self.account_url,
                credential=self.credential
            )
            self.container_client = self.blob_service_client.get_container_client(
                container=self.container_name
            )
            
            # Ensure container exists
            self._ensure_container_exists()
            
            logging.info(f"✅ Blob storage service initialized: {self.account_url}")
            
        except Exception as e:
            logging.error(f"❌ Failed to initialize blob storage: {str(e)}")
            raise
    
    def _ensure_container_exists(self):
        """Create container if it doesn't exist."""
        try:
            # Try to get container properties (this will fail if container doesn't exist)
            self.container_client.get_container_properties()
            logging.info(f"📦 Container '{self.container_name}' exists")
        except Exception:
            try:
                # Container doesn't exist, create it
                self.container_client.create_container()
                logging.info(f"📦 Created container '{self.container_name}'")
            except Exception as e:
                if "ContainerAlreadyExists" not in str(e):
                    logging.error(f"❌ Failed to create container: {str(e)}")
                    raise
    
    def _generate_blob_path(self, session_id: str, filename: str, date: str = None, subfolder: str = None) -> str:
        logging.info(f"Generating blob path funciton called for session_id={session_id}, filename={filename}, date={date}, subfolder={subfolder}")
        """
        Generate blob path with folder structure: {session-id}/{subfolder or date}/{file}
        
        Args:
            session_id: Session identifier
            filename: File name
            date: Date string (YYYY-MM-DD), defaults to today (used when subfolder is None)
            subfolder: Optional subfolder name (e.g., 'user-uploads'). If provided, overrides date-based structure
            
        Returns:
            Full blob path
        """
        # Sanitize inputs to prevent path issues
        session_id = session_id.replace('/', '_').replace('\\', '_')
        filename = os.path.basename(filename)  # Remove any path components
        
        if subfolder:
            # Use subfolder structure: {session-id}/{subfolder}/{file}
            subfolder = subfolder.replace('/', '_').replace('\\', '_')
            return f"{session_id}/{subfolder}/{filename}"
        else:
            # Use date-based structure: {session-id}/{date}/{file}
            if not date:
                date = datetime.now().strftime("%Y-%m-%d")
            return f"{session_id}/{date}/{filename}"
    
    def upload_file(self, 
                   session_id: str, 
                   file_content: bytes, 
                   filename: str,
                   content_type: str = None,
                   metadata: Dict[str, str] = None,
                   subfolder: str = None) -> Dict[str, Any]:
        logging.debug(f"Upload file function called for session_id={session_id}, filename={filename}, subfolder={subfolder}")
        """
        Upload file to blob storage with organized folder structure.
        
        Args:
            session_id: Session identifier
            file_content: File content as bytes
            filename: Original filename
            content_type: MIME type of the file
            metadata: Additional metadata to store with the blob
            subfolder: Optional subfolder (e.g., 'user-uploads' for user files)
            
        Returns:
            Dict containing blob URL, path, and metadata
        """
        try:
            # Generate blob path with optional subfolder
            blob_path = self._generate_blob_path(session_id, filename, subfolder=subfolder)
            
            # Prepare metadata
            blob_metadata = {
                'session_id': session_id,
                'original_filename': filename,
                'upload_timestamp': datetime.now().isoformat(),
                'file_size': str(len(file_content))
            }
            if metadata:
                blob_metadata.update(metadata)
            
            # Determine content type
            if not content_type:
                content_type = self._get_content_type(filename)
            
            # Upload blob
            blob_client = self.container_client.get_blob_client(blob_path)
            blob_client.upload_blob(
                data=file_content,
                content_type=content_type,
                metadata=blob_metadata,
                overwrite=True
            )
            
            # Generate blob URL (direct URL)
            blob_url = blob_client.url
            
            # Generate SAS URL for secure download access
            sas_url = self.generate_sas_url(blob_path, expiry_hours=24)
            
            logging.info(f"📤 Uploaded file: {filename} -> {blob_path}, SAS URL: {sas_url}")
            
            return {
                'success': True,
                'blob_url': sas_url,  # Direct blob URL
                'sas_url': sas_url,    # SAS URL for download access
                'blob_path': blob_path,
                'filename': filename,
                'session_id': session_id,
                'content_type': content_type,
                'size': len(file_content),
                'metadata': blob_metadata
            }
            
        except AzureError as e:
            logging.error(f"❌ Azure error uploading {filename}: {str(e)}")
            return {
                'success': False,
                'error': f"Azure storage error: {str(e)}",
                'filename': filename
            }
        except Exception as e:
            logging.error(f"❌ Error uploading {filename}: {str(e)}")
            return {
                'success': False,
                'error': f"Upload error: {str(e)}",
                'filename': filename
            }
    
    def generate_sas_url(
        self,
        blob_path: str,
        expiry_hours: int = 24,
    ) -> str:
        """
        Generate a SAS URL for an existing blob using a user-delegation key.
        This produces a read-only link clients can use to download the file.
        """
        # Blob client for URL construction
        blob_client = self.container_client.get_blob_client(blob_path)

        # When the user-delegation key itself is valid
        key_start = datetime.utcnow()
        key_expiry = key_start + timedelta(hours=expiry_hours)

        # Get user-delegation key (using your AAD identity via DefaultAzureCredential)
        user_delegation_key = self.blob_service_client.get_user_delegation_key(
            key_start_time=key_start,
            key_expiry_time=key_expiry,
        )

        # SAS expiry (you can make this shorter than the key lifetime if you want)
        sas_expiry = datetime.utcnow() + timedelta(hours=expiry_hours)

        # Generate SAS token signed with the user-delegation key
        sas_token = generate_blob_sas(
            account_name=self.blob_service_client.account_name,
            container_name=self.container_name,
            blob_name=blob_path,
            user_delegation_key=user_delegation_key,
            permission=BlobSasPermissions(read=True),  # read-only SAS
            expiry=sas_expiry,
        )

        # Full SAS URL that clients can use to download
        return f"{blob_client.url}?{sas_token}"
    
    def list_session_files(self, session_id: str, date: str = None) -> list:
        """
        List all files for a specific session and optional date.
        
        Args:
            session_id: Session identifier
            date: Optional date filter (YYYY-MM-DD)
            
        Returns:
            List of file information dictionaries
        """
        try:
            prefix = f"{session_id}/"
            if date:
                prefix = f"{session_id}/{date}/"
            
            blobs = self.container_client.list_blobs(name_starts_with=prefix)
            
            files = []
            for blob in blobs:
                files.append({
                    'name': blob.name,
                    'url': f"{self.account_url}{self.container_name}/{blob.name}",
                    'size': blob.size,
                    'last_modified': blob.last_modified,
                    'metadata': blob.metadata
                })
            
            return files
            
        except Exception as e:
            logging.error(f"❌ Error listing files for session {session_id}: {str(e)}")
            return []
    

    def _get_content_type(self, filename: str) -> str:
        logging.info(f"Getting content type function called for filename={filename}")
        """
        Determine content type based on file extension.
        
        Args:
            filename: File name
            
        Returns:
            MIME type string
        """
        ext = os.path.splitext(filename.lower())[1]
        
        content_types = {
            '.png': 'image/png',
            '.jpg': 'image/jpeg',
            '.jpeg': 'image/jpeg',
            '.gif': 'image/gif',
            '.pdf': 'application/pdf',
            '.json': 'application/json',
            '.txt': 'text/plain',
            '.csv': 'text/csv',
            '.xlsx': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
            '.docx': 'application/vnd.openxmlformats-officedocument.wordprocessingml.document'
        }
        
        return content_types.get(ext, 'application/octet-stream')
    
    def get_blob_info(self, blob_path: str) -> Optional[Dict[str, Any]]:
        logging.info(f"Getting blob info function called for blob_path={blob_path}")
        """
        Get information about a specific blob.
        
        Args:
            blob_path: Path to the blob
            
        Returns:
            Blob information dictionary or None if not found
        """
        try:
            blob_client = self.container_client.get_blob_client(blob_path)
            properties = blob_client.get_blob_properties()
            
            return {
                'name': blob_path,
                'url': blob_client.url,
                'size': properties.size,
                'content_type': properties.content_settings.content_type,
                'last_modified': properties.last_modified,
                'metadata': properties.metadata
            }
            
        except Exception as e:
            logging.error(f"❌ Error getting blob info for {blob_path}: {str(e)}")
            return None
    
